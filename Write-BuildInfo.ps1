#Requires -Version 5.1
<#
.SYNOPSIS
    Writes BuildInfo.h with the current git short commit hash.

.DESCRIPTION
    Run as the project's pre-build step and again by Make-BuildZip.ps1 before
    packaging. In Debug builds the hash gets "-dirty" appended when tracked
    files have uncommitted changes. Release builds never show "-dirty"; when a
    Release build comes from uncommitted changes the hash is the base commit
    and the build output carries a warning (BI001) instead, so commit before
    building a release to make the hash exact.

    Deployed builds are compiled on the target machine from the source zip,
    which carries no .git. There the BuildInfo.h stamped into the zip at
    packaging time is left as-is. "unknown" is written only when there is
    neither a repository nor an existing BuildInfo.h.

    The file is rewritten only when its content changes, so an unchanged hash
    does not force a recompile.

.PARAMETER OutFile
    Path of the header to write.

.PARAMETER Configuration
    The build configuration ($(Configuration) in the pre-build step). "Release"
    drops the "-dirty" suffix (see above); anything else keeps it.

.PARAMETER RepoDir
    Directory to ask git about. Defaults to the header's own directory (git
    searches upward from there for the repository).
#>
param(
    [Parameter(Mandatory = $true)][string]$OutFile,
    [string]$RepoDir,
    [string]$Configuration
)

$ErrorActionPreference = 'Stop'

# Resolved against the PowerShell location, not the process's working directory.
$OutFile = $ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($OutFile)
if (-not $RepoDir) { $RepoDir = Split-Path $OutFile -Parent }

$hash = $null
if (Get-Command git -ErrorAction SilentlyContinue) {
    # git prints CRLF-conversion warnings on stderr; they are not failures.
    $ErrorActionPreference = 'Continue'
    $h = & git -C $RepoDir rev-parse --short HEAD 2>$null
    if ($LASTEXITCODE -eq 0 -and $h) {
        $hash = "$h".Trim()
        $dirty = & git -C $RepoDir status --porcelain --untracked-files=no 2>$null
        if ($LASTEXITCODE -eq 0 -and $dirty) {
            if ($Configuration -eq 'Release') {
                # Release builds don't show "-dirty"; say so in the build output.
                Write-Host "Write-BuildInfo : warning BI001: Release build from uncommitted changes; version string shows base commit $hash. Commit before building a release."
            } else {
                $hash += '-dirty'
            }
        }
    }
    $ErrorActionPreference = 'Stop'
}

if (-not $hash) {
    if (Test-Path -LiteralPath $OutFile) {
        # Keep the packaged hash, but make sure the file ends in a newline:
        # the resource compiler (the .rc2 includes it through Version.h)
        # fails with RC1004 on a last line without one.
        $kept = [System.IO.File]::ReadAllText($OutFile)
        if (-not $kept.EndsWith("`n")) { [System.IO.File]::WriteAllText($OutFile, $kept + "`r`n") }
        Write-Host "Write-BuildInfo: no git repository; keeping $(Split-Path $OutFile -Leaf) as packaged"
        exit 0
    }
    $hash = 'unknown'
}

$content = @"
// Generated by Write-BuildInfo.ps1 -- do not edit and do not commit.
// Version.h holds the hand-maintained version number.
#pragma once
#define BUILD_GIT_HASH "$hash"
"@
# Trailing newline: rc.exe (RC1004) rejects an included header whose last line has none.
$content += "`r`n"

$existing = if (Test-Path -LiteralPath $OutFile) { [System.IO.File]::ReadAllText($OutFile) } else { $null }
if ($existing -ne $content) {
    [System.IO.File]::WriteAllText($OutFile, $content)
    Write-Host "Write-BuildInfo: $(Split-Path $OutFile -Leaf) -> $hash"
} else {
    Write-Host "Write-BuildInfo: $(Split-Path $OutFile -Leaf) unchanged ($hash)"
}
exit 0
